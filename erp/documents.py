def _format_body(content):
    purpose, steps, notes = content
    procedure = "\n".join(f"{number}. {step}" for number, step in enumerate(steps, start=1))
    return f"## 목적 및 적용 범위\n{purpose}\n\n## 업무 절차\n{procedure}\n\n## 유의 사항\n{notes}"



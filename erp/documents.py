def _format_internal_document(title, revision=None):
    number, owner, heading, standard, example = _DOCUMENT_STANDARDS[title]
    previous = _format_body(_DOCUMENT_CONTENT[title])
    version = "1.1" if revision else "1.0"
    effective_date = f"@시행일: {revision[0]}\n" if revision else ""
    history = (
        f"\n\n## 개정 이력\n1.1 · {revision[0]} — {revision[1]}\n1.0 — 최초 등록"
        if revision else ""
    )
    return (
        f"@문서번호: {number}\n@소관 부서: {owner}\n@개정: {version}\n{effective_date}"
        f"@문서 상태: 시연용\n\n{previous}\n\n"
        f"## {heading}\n{standard}\n\n## 업무 기록 양식\n{example}{history}"
    )


